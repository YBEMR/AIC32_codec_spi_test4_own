/*
**************************************************************************
*
*  Function    : D_plsf_reset
*  Purpose     : Resets state memory
*
**************************************************************************
*/
void D_plsf_reset (D_plsfState *state)
{
  Word16 i;
  
  for (i = 0; i < M; i++){
      state->past_r_q[i] = 0;             /* Past quantized prediction error */
  }
  
  /* Past dequantized lsfs */
  Copy(mean_lsf, &state->past_lsf_q[0], M);
}
